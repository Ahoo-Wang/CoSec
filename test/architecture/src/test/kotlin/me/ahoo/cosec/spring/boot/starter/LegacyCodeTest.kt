/** The G1 rules, shared with `LegacyCodeGuardTest`, which checks them against fixtures. */
internal object Guards {
    /**
     * Kotlin marks two kinds of generated members `java.lang.Deprecated` by itself: the static field of a companion's
     * private constant, and the `DefaultImpls` bridges of an interface's default methods. Nobody wrote those
     * annotations, so they are not ones G1 forbids.
     */
    private val generatedByKotlin = object : DescribedPredicate<JavaMember>("generated by the Kotlin compiler") {
        override fun test(member: JavaMember): Boolean = member.owner.simpleName == "DefaultImpls" ||
            member is JavaField &&
            member.modifiers.containsAll(listOf(JavaModifier.STATIC, JavaModifier.FINAL)) &&
            member.owner.fields.any { it.name == "Companion" }
    }

    val noDeprecatedClass: ArchRule = noClasses()
        .should().beAnnotatedWith(Deprecated::class.java)
        .orShould().beAnnotatedWith(java.lang.Deprecated::class.java)
        .because("8.0 removes what it replaces (G1)")

    val noDeprecatedMember: ArchRule = noMembers()
        .that(DescribedPredicate.not(generatedByKotlin))
        .should().beAnnotatedWith(Deprecated::class.java)
        .orShould().beAnnotatedWith(java.lang.Deprecated::class.java)
        .because("8.0 removes what it replaces (G1)")
}

/**
 * The guards against code 8.0 no longer uses (RFC 0008 §4.6.2), over every module the starter wires: this test
 * classpath holds them all. G2, no transition comments, is detekt's `ForbiddenComment` (`config/detekt/detekt.yml`).
 */
@AnalyzeClasses(packages = ["me.ahoo.cosec"], importOptions = [DoNotIncludeTests::class])
class LegacyCodeTest {
    /** G1: nothing is kept for compatibility behind `@Deprecated`; a replaced API is removed. */
    @ArchTest
    val noDeprecatedClass: ArchRule = Guards.noDeprecatedClass

    @ArchTest
    val noDeprecatedMember: ArchRule = Guards.noDeprecatedMember

    /** G7: migration and compatibility code lives in `cosec-migrate` only. */
    @ArchTest
    val noMigrationCodeOutsideMigrate: ArchRule = noClasses()
        .that().resideOutsideOfPackage("$MIGRATE..")
        .should().haveSimpleNameContaining("Migration")
        .orShould().haveSimpleNameContaining("Legacy")
        .orShould().haveSimpleNameContaining("Compat")
        .because("converting earlier data is cosec-migrate's job (G7)")

    /**
     * G5 for `cosec-api`, the thin contract module: each of its types is used by some other module's `main` code, through
     * the type, one of its nested classes, or an api type that extends it (callers see `CoSecPrincipal`, not
     * `RoleCapable`). Holders of constants only are left out: the compiler inlines their values at each use.
     */
    @ArchTest
    val everyApiTypeIsUsedOutsideApi: ArchRule = classes()
        .that().resideInAPackage("$API..")
        .should(UsedOutsideApi())
        .because("cosec-api holds only the contracts 8.0 uses (G5)")

    private class UsedOutsideApi : ArchCondition<JavaClass>("be used outside cosec-api") {
        private var used: Set<String> = emptySet()

        override fun init(allObjectsToTest: Collection<JavaClass>) {
            val directly = allObjectsToTest.filter { type ->
                type.directDependenciesToSelf.any { !it.originClass.packageName.isApi() }
            }.map { it.topLevel() }
            val all = HashSet<String>()
            val pending = ArrayDeque(allObjectsToTest.filter { it.topLevel() in directly })
            while (pending.isNotEmpty()) {
                val type = pending.removeFirst()
                if (all.add(type.name)) {
                    (type.rawInterfaces + listOfNotNull(type.rawSuperclass.orElse(null)))
                        .filter { it.packageName.isApi() }
                        .forEach(pending::add)
                }
            }
            used = all.map { it.substringBefore('$') }.toSet() + directly
        }

        override fun check(item: JavaClass, events: ConditionEvents) {
            if (!item.isTopLevelClass || item.holdsConstantsOnly() || item.name in used) {
                return
            }
            events.add(SimpleConditionEvent.violated(item, "${item.name} is used by no main class outside cosec-api"))
        }

        private fun JavaClass.topLevel(): String = name.substringBefore('$')

        private fun String.isApi(): Boolean = this == API || startsWith("$API.")

        private fun JavaClass.holdsConstantsOnly(): Boolean =
            methods.none { !it.modifiers.contains(JavaModifier.SYNTHETIC) && it.name != "<clinit>" } &&
                fields.all { it.modifiers.containsAll(listOf(JavaModifier.STATIC, JavaModifier.FINAL)) }
    }

    private companion object {
        const val API = "me.ahoo.cosec.api"
        const val MIGRATE = "me.ahoo.cosec.migrate"
    }
}
